"""Generate the kiosk's flash-resident JPEGs from images/faces/<MSSV>.*.

Run from any directory: python esp32_kiosk/tools/generate_avatars.py
Requires Pillow. Re-run and flash the firmware after changing source portraits.
Original images are never modified; jpg, jpeg, then png are preferred per MSSV.
"""
import argparse
import hashlib
import io
import re
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'images' / 'faces'
OUTPUT = ROOT / 'esp32_kiosk' / 'kiosk_avatars.h'
EXTENSIONS = ('.jpg', '.jpeg', '.png')


def build_header():
    portraits = {}
    for path in sorted(SOURCE.iterdir()):
        if not re.fullmatch(r'[0-9]{9}', path.stem) or path.suffix.lower() not in EXTENSIONS:
            continue
        previous = portraits.get(path.stem)
        if previous is None or EXTENSIONS.index(path.suffix.lower()) < EXTENSIONS.index(previous.suffix.lower()):
            portraits[path.stem] = path
    if not portraits:
        raise ValueError('No portraits with nine-digit MSSV filenames found')

    lines = ['// Generated by tools/generate_avatars.py; do not edit by hand.',
             '// Source portraits: images/faces. Re-generate and flash after changing photos.',
             '#pragma once', '#include <Arduino.h>', '#include <string.h>', '',
             'struct KioskAvatar { const char* mssv; const uint8_t* data; uint32_t size; };', '']
    total = 0
    for mssv, path in sorted(portraits.items()):
        with Image.open(path) as source:
            portrait = ImageOps.exif_transpose(source).convert('RGBA')
            portrait.thumbnail((100, 100), Image.Resampling.LANCZOS)
            canvas = Image.new('RGB', (100, 100), (0, 0, 0))
            canvas.paste(portrait, ((100-portrait.width)//2, (100-portrait.height)//2), portrait)
            stream = io.BytesIO()
            canvas.save(stream, 'JPEG', quality=75, subsampling=2, progressive=False, optimize=False)
        data = stream.getvalue()
        total += len(data)
        lines += [f'// {path.name}; source sha256: {hashlib.sha256(path.read_bytes()).hexdigest()}',
                  f'static const uint8_t kiosk_avatar_{mssv}[] PROGMEM = {{']
        lines += ['  ' + ', '.join(f'0x{byte:02x}' for byte in data[i:i+16]) + ','
                  for i in range(0, len(data), 16)]
        lines += ['};', '']
    if total > 128 * 1024:
        raise ValueError(f'Portrait data exceeds 128 KiB budget: {total} bytes; check firmware flash budget')
    lines += ['static const KioskAvatar kioskAvatars[] = {']
    lines += [f'  {{"{mssv}", kiosk_avatar_{mssv}, sizeof(kiosk_avatar_{mssv})}},'
              for mssv in sorted(portraits)]
    lines += ['};', '', 'inline const KioskAvatar* findKioskAvatar(const char* mssv) {',
              '  for (const auto& avatar : kioskAvatars) {',
              '    if (strcmp(avatar.mssv, mssv) == 0) return &avatar;',
              '  }', '  return nullptr;', '}', '']
    return '\n'.join(lines), len(portraits), total


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if the generated header is stale')
    args = parser.parse_args()
    header, count, total = build_header()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != header:
            raise SystemExit('Header is stale; run generate_avatars.py and build again')
    else:
        OUTPUT.write_text(header, encoding='utf-8', newline='\n')
    print(f'{"CHECK PASS" if args.check else "Generated"}: {count} portraits, {total} JPEG bytes')
